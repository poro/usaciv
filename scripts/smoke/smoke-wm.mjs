import { readFileSync } from "node:fs";
const R = new URL("../../", import.meta.url).pathname;
const { buildPool, dailyAnswers, practiceAnswers } = await import(R + "web/js/games/whichMetro/sim/puzzle.js");
const { newGame, guess, reveal, nextRound, totalScore } = await import(R + "web/js/games/whichMetro/sim/game.js");
const { dailyPayload, finishMsg, progressMsg, boardRows } = await import(R + "web/js/games/whichMetro/online.js");
const B = process.env.USACIV_URL || "http://localhost:8788";
const pool = buildPool(JSON.parse(readFileSync(R + "web/data/cities.json")));
const req = async (m, p, body, tok) => { const r = await fetch(B + p, { method: m, headers: { "Content-Type": "application/json", ...(tok ? { Authorization: `Bearer ${tok}` } : {}) }, body: body ? JSON.stringify(body) : undefined }); return [r.status, await r.json().catch(() => null)]; };
const play = (answers, mode, key, seed) => { let g = newGame({ mode, key, seed, answers }); g = guess(g, answers[0]); g = nextRound(g); g = reveal(g); g = guess(g, answers[1]); g = nextRound(g); for (let k = 2; k < 5; k++) { for (let j = 0; j < 5; j++) g = reveal(g); g = nextRound(g); } return g; };
const bad = await req("POST", "/api/player", { name: "x" }); console.log("bad name", bad);
const [, a] = await req("POST", "/api/player", { name: "Smoke A" });
const [, b] = await req("POST", "/api/player", { name: "Smoke B" });
const key = new Date().toISOString().slice(0, 10);
const g = play(dailyAnswers(pool, key), "daily", key);
console.log("local score", totalScore(g), "submit", await req("POST", "/api/wm/daily", dailyPayload(g), a.token));
console.log("resubmit", await req("POST", "/api/wm/daily", dailyPayload(g), a.token));
const [, board] = await req("GET", `/api/wm/daily/${key}?limit=10`, null, a.token);
console.log("board", board.total, board.you, boardRows(board.top, board.you, a.name).slice(0, 3), board.histogram.length);
const [, { code }] = await req("POST", "/api/wm/race", {}, a.token);
console.log("race", code, await req("GET", `/api/wm/race/${code}`));
const open = (tok, tag) => new Promise((res) => { const ws = new WebSocket(`ws://localhost:8789/api/wm/race/${code}/ws?token=${tok}`); ws.last = null; ws.onmessage = (e) => { const m = JSON.parse(e.data); ws.last = m; if (m.t !== "room") console.log(tag, m); }; ws.onopen = () => res(ws); ws.onclose = (e) => console.log(tag, "closed", e.code, e.reason); });
const wa = await open(a.token, "A"), wb = await open(b.token, "B");
const wait = (ms) => new Promise((r) => setTimeout(r, ms));
await wait(300);
console.log("lobby", wa.last.room.status, wa.last.room.players.map((p) => [p.name, p.online]));
wb.send(JSON.stringify({ t: "start" })); await wait(200);
wa.send(JSON.stringify({ t: "start" })); await wait(300);
const room = wa.last.room; console.log("status", room.status, "seed", room.seed);
const answers = practiceAnswers(pool, room.seed);
let ga = newGame({ mode: "race", seed: room.seed, answers }); ga = reveal(ga);
wa.send(JSON.stringify(progressMsg(ga))); await wait(300);
console.log("progress seen by B", wb.last.room.players.map((p) => [p.name, p.round, p.clues, p.score]));
const fa = play(answers, "race", null, room.seed), fb = play(answers.slice(), "race", null, room.seed);
wa.send(JSON.stringify(finishMsg(fa))); await wait(300);
wb.send(JSON.stringify(finishMsg(fb))); await wait(400);
console.log("final", wb.last.room.status, wb.last.room.players.map((p) => [p.name, p.score, p.place, p.done]), "local", totalScore(fa));
// a late joiner is refused
const [, c] = await req("POST", "/api/player", { name: "Smoke C" });
await open(c.token, "C"); await wait(400);
wa.close(); wb.close(); await wait(200);
for (const [p, n] of [[a, "Smoke A"], [b, "Smoke B"], [c, "Smoke C"]]) console.log("delete", n, (await req("DELETE", "/api/account", { confirm: n }, p.token))[0]);
process.exit(0);
