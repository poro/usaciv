import { readFileSync } from "node:fs";
const R = new URL("../../", import.meta.url).pathname;
const B = process.env.USACIV_URL || "https://usaciv.mark-ollila.workers.dev";
const S = await import(R + "web/js/games/founders/sim/index.js");
const { botTurn } = await import(R + "web/js/games/founders/sim/advice.js");
const D = (n) => JSON.parse(readFileSync(R + `web/data/${n}.json`));
const world = D("world");
const env = S.makeEnv({ world, resources: D("resources"), hazards: S.buildHazards(D("disasters"), world) });
const key = new Date().toISOString().slice(0, 10);
let s = S.newDaily(env, key); const log = [];
while (s.phase !== "over") s = botTurn(env, s, { log });
const call = async (m, p, body, token) => { const r = await fetch(B + p, { method: m, headers: { Origin: B, "Content-Type": "application/json", ...(token ? { Authorization: `Bearer ${token}` } : {}) }, body: body ? JSON.stringify(body) : undefined }); return { s: r.status, d: await r.json().catch(() => null) }; };
const me = (await call("POST", "/api/player", { name: "Smoke Test" })).d;
console.log("local score", S.prosperity(env, s).score);
console.log("submit", JSON.stringify(await call("POST", "/api/fd/daily", { key, log }, me.token)));
console.log("board", JSON.stringify((await call("GET", `/api/fd/daily/${key}`, undefined, me.token)).d));
console.log("stats", JSON.stringify((await call("GET", "/api/account/stats", undefined, me.token)).d));
console.log("delete", JSON.stringify(await call("DELETE", "/api/account", { confirm: "Smoke Test" }, me.token)));
console.log("board after", JSON.stringify((await call("GET", `/api/fd/daily/${key}`)).d));
